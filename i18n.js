    const supported = value => typeof value === 'string' && Object.hasOwn(messages, value);
    function detectLanguage() {
        const preferred = navigator.languages?.length ? navigator.languages : [navigator.language];
        for (const locale of preferred) {
            const normalized = String(locale || '').toLowerCase();
            // Traditional Chinese for Hong Kong/Taiwan/Macao or an explicit Hant script.
            // A Simplified Chinese preference must not silently select a different script.
            if (/^zh-(hant(?:-|$)|(?:hk|tw|mo)$)/.test(normalized) && !normalized.includes('-hans')) return 'zh-Hant';
            const base = normalized.split('-')[0];
            if (supported(base)) return base;
        }
        return 'en';
    }
    function t(key, values = {}) {
        const template = messages[language][key] ?? messages.en[key] ?? key;
        return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
    }
