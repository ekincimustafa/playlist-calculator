    function apply() {
        language = preference === 'auto' ? detectLanguage() : preference;
        document.documentElement.lang = language;
        document.documentElement.dir = ['ar', 'ur'].includes(language) ? 'rtl' : 'ltr';
        document.title = t('pageTitle');
        document.querySelectorAll('[data-i18n]').forEach(element => { element.textContent = t(element.dataset.i18n); });
        for (const attribute of ['placeholder', 'title', 'aria-label', 'content']) {
            document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
                element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
            });
        }
        const select = document.getElementById('languageSelect');
        if (select) select.value = preference;
        window.dispatchEvent(new Event('playlist-language-change'));
    }
